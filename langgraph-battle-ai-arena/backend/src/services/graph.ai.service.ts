import { StateSchema, StateGraph, START, END, type GraphNode } from "@langchain/langgraph";
import { cohereModel, groqModel, cloudflareModel } from "./models.service.js";
import { createAgent, providerStrategy, HumanMessage } from "langchain";
import z from "zod";

const ArenaState = new StateSchema({
  problem: z.string().default(""),
  solution_1: z.string().default(""),
  solution_2: z.string().default(""),
  judge: z.object({
    solution_1_score: z.number().default(0),
    solution_2_score: z.number().default(0),
    solution_1_reasoning: z.string().default(""),
    solution_2_reasoning: z.string().default(""),
  }),
});

const generateSolutionsNode: GraphNode<typeof ArenaState> = async (state) => {
  const [cohereResponse, groqResponse] = await Promise.all([
    cohereModel.invoke(state.problem),
    groqModel.invoke(state.problem),
  ]);

  return {
    solution_1: cohereResponse.text,
    solution_2: groqResponse.text,
  };
};

const judgeSolutionsNode: GraphNode<typeof ArenaState> = async (state) => {
  const { problem, solution_1, solution_2 } = state;

  const judgeAgent = createAgent({
    model: cloudflareModel,
    responseFormat: providerStrategy(
      z.object({
        solution_1_score: z.number().min(0).max(10),
        solution_2_score: z.number().min(0).max(10),
        solution_1_reasoning: z.string(),
        solution_2_reasoning: z.string(),
      })
    ),
    systemPrompt: `You are a judge tasked with evaluating two solutions generated by different AI models. Please provide a score out of 10 for each solution, along with your reasoning for the scores.`,
  });

  const judgeResponse = await judgeAgent.invoke({
    messages: [
      new HumanMessage(`
        Problem: ${problem}
        Solution 1: ${solution_1}
        Solution 2: ${solution_2}
        Please evaluate the solutions and provide scores and reasoning.
      `),
    ],
  });

  const {
    solution_1_score,
    solution_2_score,
    solution_1_reasoning,
    solution_2_reasoning,
  } = judgeResponse.structuredResponse;

  return {
    judge: {
      solution_1_score,
      solution_2_score,
      solution_1_reasoning,
      solution_2_reasoning,
    },
  };
};

const arenaGraph = new StateGraph(ArenaState)
  .addNode("generate_solutions", generateSolutionsNode)
  .addNode("judge_solutions", judgeSolutionsNode)
  .addEdge(START, "generate_solutions")
  .addEdge("generate_solutions", "judge_solutions")
  .addEdge("judge_solutions", END)
  .compile();

export default async function runArenaGraph(problem: string) {
  const result = await arenaGraph.invoke({
    problem,
  });

  return result;
}
